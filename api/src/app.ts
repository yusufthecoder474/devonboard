import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import swaggerUi from 'swagger-ui-express';
import { readFileSync } from 'fs';
import YAML from 'yaml';
import authRoutes from './routes/auth.js';
import keyRoutes from './routes/keys.js';
import sandboxRoutes from './routes/sandbox.js';
import dashboardRoutes from './routes/dashboard.js';
import funnelRoutes from './routes/funnel.js';
import eventRoutes from './routes/events.js';
export const app = express();
app.use(cors({ origin: process.env.CORS_ORIGIN || 'http://localhost:5173', credentials: true }));
app.use(express.json());
app.use(cookieParser());
app.get('/health', (_req, res) => res.json({ ok: true }));
app.use('/docs', swaggerUi.serve, swaggerUi.setup(YAML.parse(readFileSync(new URL('../openapi.yaml', import.meta.url), 'utf8'))));
app.use('/api/auth', authRoutes);
app.use('/api/keys', keyRoutes);
app.use('/api/dashboard', dashboardRoutes);
app.use('/api/admin', funnelRoutes);
app.use('/api/events', eventRoutes);
app.use('/v1', sandboxRoutes);
app.use((_req, res) => res.status(404).json({ error: { code: 'NOT_FOUND', message: 'Route not found' } }));
app.use((err: any, _req: any, res: any, _next: any) => res.status(500).json({ error: { code: 'INTERNAL', message: err?.message || 'Internal error' } }));
export default app;
